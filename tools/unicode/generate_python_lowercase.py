# Generates src/SecretModel.Core/Text/PythonLowercaseData.g.cs: the data the C# needs to lowercase
# text exactly as Python's str.lower() does (README SM-TOK-008). It records Python's behavior,
# measured by calling str.lower(); it does not restate Unicode rules from memory.
#
#   1. Every code point whose str.lower() differs from itself, and what it becomes.
#   2. For the one context-dependent rule (capital sigma at the end of a word becomes final sigma),
#      which code points the rule skips over ("case-ignorable") and which count as letters ("cased").
#      Both are read from str.lower() with probe strings, as explained in classify() below.
#
# The definition is locked to Unicode 15.1 (Python 3.13). The script refuses to run on any other
# version, because a different table would change merchant tokens.
# Run from the repository root:   python3 -I tools/unicode/generate_python_lowercase.py

import os
import sys
import unicodedata

LOCKED_UNICODE_VERSION = "15.1.0"
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(REPO, "src", "SecretModel.Core", "Text", "PythonLowercaseData.g.cs")

CAPITAL_SIGMA = "Σ"
FINAL_SIGMA = "ς"


def code_points():
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue  # surrogates are not characters; C# leaves them unchanged, as Python does
        yield cp


def classify(c):
    # Python turns a capital sigma into a final sigma when a cased letter comes before it (skipping
    # case-ignorable characters) and no cased letter follows it (again skipping case-ignorable ones).
    #   c + SIGMA       ends in final sigma  <=>  c is not ignorable and is cased
    #   "A" + c + SIGMA ends in final sigma  <=>  c is ignorable, or c is cased
    # An ignorable character is always skipped, so whether it is also cased never matters.
    if (c + CAPITAL_SIGMA).lower().endswith(FINAL_SIGMA):
        return "cased"
    if ("A" + c + CAPITAL_SIGMA).lower().endswith(FINAL_SIGMA):
        return "ignorable"
    return "neither"


def ranges(cps):
    out = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def cs_string(s):
    parts = []
    for ch in s:
        o = ord(ch)
        if 0x20 <= o <= 0x7E and ch not in '"\\':
            parts.append(ch)
        elif o <= 0xFFFF:
            parts.append("\\u%04X" % o)
        else:
            parts.append("\\U%08X" % o)
    return '"' + "".join(parts) + '"'


def int_lines(values, per_line=8):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("        " + ", ".join("0x%X" % v for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    if unicodedata.unidata_version != LOCKED_UNICODE_VERSION:
        sys.exit(f"This Python uses Unicode {unicodedata.unidata_version}; the table is locked to "
                 f"{LOCKED_UNICODE_VERSION} (Python 3.13). Use Python 3.13.")

    mappings = []
    ignorable = []
    cased = []
    for cp in code_points():
        c = chr(cp)
        lowered = c.lower()
        if lowered != c:
            mappings.append((cp, lowered))
        kind = classify(c)
        if kind == "ignorable":
            ignorable.append(cp)
        elif kind == "cased":
            cased.append(cp)

    ign_ranges = ranges(ignorable)
    cased_ranges = ranges(cased)

    to_lines = []
    for i in range(0, len(mappings), 8):
        to_lines.append("        " + ", ".join(cs_string(t) for _, t in mappings[i:i + 8]) + ",")

